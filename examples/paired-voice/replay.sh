#!/bin/sh
# Re-execute the ten registered fixes and their reversals, then run both native passes.
set -eu
test "$#" = 4 || { echo 'Usage: sh replay.sh REPOS_BY_OWNER MODEL.gguf TOKENIZER.gguf NEW_OUTPUT_DIR' >&2; exit 2; }
repos=$1 weights=$2 tokenizer=$3 out=$4
dir=examples/paired-voice
case $out in /*) ;; ?*) out=./$out;; *) exit 2;; esac
name=$(basename "$out")
parent=$(dirname "$out")
case $name in .|..|/) exit 2;; esac
out=$parent/$name
if test -e "$out" || test -L "$out"; then echo "Output exists: $out" >&2; exit 1; fi
mkdir -p "$parent"
work=$(mktemp -d "$parent/.voice-replay.XXXXXXXX")
trap 'rm -rf "$work"' EXIT
trap 'exit 1' HUP INT TERM
# Select the registered PRs before either corpus builder reads Git objects.
sh examples/threshold-transfer/corpus.sh "$repos" "$work/train" "$dir/references.tsv"
sh examples/release-trial/corpus.sh "$repos/benhoyt/inih" "$repos/npm/node-semver" "$work/held" "$dir/probes.tsv"
for split in train held; do
    # Keep original input bytes for positive witness modes, in the panel's native order.
    jq -Rr 'select((fromjson.trace_evidence.runs[0].mode // 0) > 0)' \
        "$work/$split/inputs.jsonl" >> "$work/inputs"
done
test "$(wc -l < "$work/inputs")" -eq 20
build/jovovich "$weights" "$tokenizer" --json < "$work/inputs" > "$work/votes"
sh "$dir/packets.sh" "$work/packets" "$work/votes"
build/voice-pilot --baseline "$weights" "$tokenizer" "$work/packets/heldout.jsonl" > "$work/voice"
sh "$dir/verify.sh" "$work/packets" "$work/voice"
cmp "$work/voice" "$dir/base.json"
result=$work/result
mkdir -p "$result"
mv "$work/inputs" "$result/inputs.jsonl"
mv "$work/votes" "$result/votes.jsonl"
mv "$work/voice" "$result/base.json"
sh tools/publish_directory.sh "$work" "$result" "$out"
echo '20 executed reviews, eight complete token streams and their exact generated bytes reproduced'
